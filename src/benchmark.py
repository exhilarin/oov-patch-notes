"""Step 5: collect every results/*.json into results/benchmark.md and draw the figures.

Primary metric: span-level macro-F1 (seqeval, strict IOB2): a predicted change counts only
if its first token, last token and type are all correct, and every type weighs the same.
"""
import json
from collections import Counter

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from common import DATA, RESULTS, TYPES, load

BLUE, ORANGE, INK, MUTED, GRID = "#2f6fb0", "#e08a2c", "#1d1d1b", "#52514e", "#e4e3df"
ORDER = ["keyword_rules", "crf", "bilstm_crf", "bert", "deberta", "modernbert",
         "laya_zero_shot_crf_spans", "laya_zero_shot_oracle_spans"]
NAMES = {"keyword_rules": "Keyword rules", "crf": "CRF", "bilstm_crf": "BiLSTM-CRF", "bert": "BERT-base",
         "deberta": "DeBERTa-v3-base", "modernbert": "ModernBERT-base",
         "laya_zero_shot_crf_spans": "Laya zero-shot (CRF spans)",
         "laya_zero_shot_oracle_spans": "Laya zero-shot (gold spans)*"}
FIG = RESULTS / "figures"


def style(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.spines["left"].set_color(GRID)
    ax.spines["bottom"].set_color(MUTED)
    ax.tick_params(colors=MUTED)
    ax.yaxis.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def fmt(s, k):
    v = s[k]
    return f"{v:.3f} ± {s[k + '_std']:.3f}" if k + "_std" in s else f"{v:.3f}"


def results():
    rs = {}
    for p in RESULTS.glob("*.json"):
        r = json.loads(p.read_text())
        rs[r["model"]] = r
    return [rs[m] for m in ORDER if m in rs]


def bar_figure(rs):
    names = [NAMES[r["model"]] for r in rs]
    a = [r["test"]["span_macro_f1"] for r in rs]
    b = [r["test_unseen_games"]["span_macro_f1"] for r in rs]
    x = np.arange(len(rs))
    fig, ax = plt.subplots(figsize=(11, 4.4))
    ax.bar(x - 0.21, a, 0.4, color=BLUE, label="random test split")
    ax.bar(x + 0.21, b, 0.4, color=ORANGE, label="unseen games")
    for xi, v in zip(x - 0.21, a):
        ax.text(xi, v + 0.01, f"{v:.2f}", ha="center", fontsize=8, color=INK)
    for xi, v in zip(x + 0.21, b):
        ax.text(xi, v + 0.01, f"{v:.2f}", ha="center", fontsize=8, color=INK)
    ax.set_xticks(x, names, rotation=18, ha="right", fontsize=9)
    ax.set_ylabel("span macro-F1", color=MUTED)
    ax.set_ylim(0, max(a + b) * 1.18)
    ax.legend(frameon=False, loc="upper left")
    style(ax)
    fig.tight_layout()
    fig.savefig(FIG / "macro_f1.png", dpi=160)
    plt.close(fig)


def per_type_figure(best):
    pt = best["test"]["per_type"]
    types = sorted(pt, key=lambda t: pt[t]["f1-score"])
    fig, ax = plt.subplots(figsize=(7, 5.6))
    v = [pt[t]["f1-score"] for t in types]
    ax.barh(types, v, color=BLUE, height=0.65)
    for i, (t, f) in enumerate(zip(types, v)):
        ax.text(f + 0.01, i, f"{f:.2f}  (n={int(pt[t]['support']):,})", va="center", fontsize=8, color=MUTED)
    ax.set_xlim(0, 1.15)
    ax.set_xlabel(f"span F1 per change type ({NAMES[best['model']]}, random test split)", color=MUTED)
    style(ax)
    ax.yaxis.grid(False)
    ax.xaxis.grid(True, color=GRID, linewidth=0.8)
    fig.tight_layout()
    fig.savefig(FIG / "per_type_f1.png", dpi=160)
    plt.close(fig)


def label_figure(counts):
    types = sorted(counts, key=counts.get)
    fig, ax = plt.subplots(figsize=(7, 5.6))
    ax.barh(types, [counts[t] for t in types], color=BLUE, height=0.65)
    for i, t in enumerate(types):
        ax.text(counts[t] * 1.01, i, f"{counts[t]:,}", va="center", fontsize=8, color=MUTED)
    ax.set_xlabel("change items in the cleaned dataset", color=MUTED)
    ax.set_xlim(0, max(counts.values()) * 1.18)
    style(ax)
    ax.yaxis.grid(False)
    fig.tight_layout()
    fig.savefig(FIG / "label_distribution.png", dpi=160)
    plt.close(fig)


def main():
    FIG.mkdir(parents=True, exist_ok=True)
    rs = results()
    splits = {s: load(s) for s in ("train", "val", "test", "test_unseen_games")}
    counts = Counter(t[2:] for rows in splits.values() for r in rows for t in r["tags"] if t.startswith("B-"))
    report = json.loads((DATA / "cleaning_report.json").read_text())["steps"]

    L = ["# Benchmark: patch-note change segmentation and typing", "",
         "Generated by `src/benchmark.py`. Primary metric: **span-level macro-F1** (seqeval, strict IOB2) over "
         f"{len(TYPES)} change types. A change counts as correct only if its boundaries and its type are both right.",
         "`boundary-F1` ignores the type and only checks the segmentation.", "", "## Data", "",
         "| Step | Count |", "|---|---|"]
    L += [f"| {k[2:].replace('_', ' ')} | {v:,} |" for k, v in report.items()]
    L += ["", "| Split | Examples | Games | Tokens |", "|---|---|---|---|"]
    for s, rows in splits.items():
        L.append(f"| {s} | {len(rows):,} | {len({r['appid'] for r in rows}):,} | {sum(len(r['tokens']) for r in rows):,} |")
    L += ["", "## Results", "",
          "| Model | Group | Test macro-F1 | Test micro-F1 | Test boundary-F1 | Unseen-games macro-F1 | Unseen-games micro-F1 |",
          "|---|---|---|---|---|---|---|"]
    for r in rs:
        t, u = r["test"], r["test_unseen_games"]
        L.append(f"| {NAMES[r['model']]} | {r['group']} | {fmt(t, 'span_macro_f1')} | {fmt(t, 'span_micro_f1')} | "
                 f"{fmt(t, 'boundary_f1')} | {fmt(u, 'span_macro_f1')} | {fmt(u, 'span_micro_f1')} |")
    L += ["", "\\* uses the gold change boundaries (an upper bound for the typing step only, not a fair competitor).",
          "Laya rows are evaluated on a random sample of each test split (see the result file).", ""]

    trained = [r for r in rs if not r["model"].startswith("laya")]
    if trained:
        best = max(trained, key=lambda r: r["val"]["span_macro_f1"])
        L += [f"## Per-type scores of the best model on validation ({NAMES[best['model']]})", "",
              "| Type | Items in data | Test F1 | Unseen-games F1 |", "|---|---|---|---|"]
        for ty in sorted(TYPES, key=lambda x: -counts[x]):
            a = best["test"]["per_type"].get(ty, {}).get("f1-score", 0)
            b = best["test_unseen_games"]["per_type"].get(ty, {}).get("f1-score", 0)
            L.append(f"| {ty} | {counts[ty]:,} | {a:.3f} | {b:.3f} |")
        per_type_figure(best)
    bar_figure(rs)
    label_figure(counts)
    L += ["", "![macro-F1 per model](figures/macro_f1.png)", "", "![per-type F1](figures/per_type_f1.png)", "",
          "![label distribution](figures/label_distribution.png)", ""]
    (RESULTS / "benchmark.md").write_text("\n".join(L))
    print("\n".join(L[:60]))


if __name__ == "__main__":
    main()
