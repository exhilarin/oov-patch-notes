"""Step 6: error analysis on the random test split (CRF model from models/crf.pkl, CPU).

* Boundary vs type errors: of the gold changes whose boundaries the CRF finds exactly, how
  many also get the right type, and which types are confused (gold -> predicted).
* Label noise: change items whose first word is a strong cue of another type ("Fixed ..." under
  an *Audio* header). These come from headers that name a game area (UI, audio, graphics)
  rather than a kind of change, so one item can honestly belong to two types.
Output: results/error_analysis.md
"""
import pickle
import random
from collections import Counter

from common import RESULTS, ROOT, load, spans
from train_classical import featurize

CUES = {"Fixed": "FIX", "Fix": "FIX", "Added": "NEW_CONTENT", "Improved": "IMPROVEMENT"}


def main():
    crf = pickle.loads((ROOT / "models/crf.pkl").read_bytes())
    rows = load("test")
    pred = crf.predict(featurize(rows))
    conf, n_gold = Counter(), 0
    for r, p in zip(rows, pred):
        g = {(a, b): t for a, b, t in spans(r["tags"])}
        q = {(a, b): t for a, b, t in spans(p)}
        n_gold += len(g)
        for k, t in g.items():
            if k in q:
                conf[(t, q[k])] += 1
    n_b = sum(conf.values())
    n_ok = sum(v for (a, b), v in conf.items() if a == b)
    per_gold = Counter()
    for (a, _), v in conf.items():
        per_gold[a] += v

    noisy, n_items = [], 0
    for r in rows:
        for a, b, t in spans(r["tags"]):
            n_items += 1
            cue = CUES.get(r["tokens"][a])
            if cue and cue != t:
                noisy.append((t, cue, " ".join(r["tokens"][a:b])))
    by_type = Counter(t for t, _, _ in noisy)

    L = ["# Error analysis (CRF, random test split)", "",
         "Generated by `src/error_analysis.py`.", "",
         "## Boundary errors vs type errors", "",
         f"* gold changes: {n_gold:,}",
         f"* boundaries found exactly: {n_b:,} ({n_b / n_gold:.1%})",
         f"* of those, type also correct: {n_ok:,} ({n_ok / n_b:.1%})", "",
         "Most frequent confusions among changes with correct boundaries:", "",
         "| Gold type | Predicted | Count | Share of the gold type |", "|---|---|---|---|"]
    for (a, b), v in sorted(((k, v) for k, v in conf.items() if k[0] != k[1]), key=lambda x: -x[1])[:12]:
        L.append(f"| {a} | {b} | {v:,} | {v / per_gold[a]:.0%} |")
    L += ["", "## Label noise from area headers", "",
          f"{len(noisy):,} of {n_items:,} test items ({len(noisy) / n_items:.1%}) start with a cue word of another "
          "type (`Fixed`/`Fix` → FIX, `Added` → NEW_CONTENT, `Improved` → IMPROVEMENT). By gold type:", "",
          "| Gold type (header) | Items starting with another type's cue |", "|---|---|"]
    L += [f"| {t} | {v:,} |" for t, v in by_type.most_common(8)]
    L += ["", "Random examples:", ""]
    for t, cue, s in random.Random(7).sample(noisy, 10):
        L.append(f"* **{t}** (reads like {cue}): {s}")
    (RESULTS / "error_analysis.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
